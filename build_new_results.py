"""Generate the representative-results table used in the manuscript.

The table intentionally reports fixed exemplars rather than a post-hoc top-k
selection. Keeping their identifiers here makes the selection rule explicit;
all objectives, certificates, statuses, and margins are read from the canonical
post-refinement result series.

Usage:
    python build_new_results.py [--csv results/adaptive_master_refined.csv]

Output:
    results/analysis/new_certified_results.tex
    results/analysis/new_certified_results.csv
"""
from __future__ import annotations

import argparse
import os

import pandas as pd


EXEMPLARS = [
    ("D_n065_026_a50", "new", "first-ever, proven optimal"),
    ("D_n075_037_a75", "new", "near-optimal large line instance"),
    ("ED_n065_026_a75", "improved", None),
    ("EB_n140_024_a50", "improved", None),
    ("EB_n140_022_a50", "improved", None),
]


def esc(value: str) -> str:
    return value.replace("_", r"\_")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default="results/adaptive_master_refined.csv")
    parser.add_argument("--outdir", default="results/analysis")
    args = parser.parse_args()

    data = pd.read_csv(args.csv)
    rows = []
    for instance, expected_status, fixed_note in EXEMPLARS:
        # The manuscript omits the final replication/group suffix from these
        # benchmark labels; resolve it only when the canonical CSV has one
        # unambiguous matching row.
        match = data[data["instance"].astype(str).str.startswith(instance + "_")]
        if len(match) != 1:
            raise SystemExit(f"expected exactly one canonical row for {instance}; found {len(match)}")
        row = match.iloc[0]
        status = str(row["beta_status"]).strip()
        bks = pd.to_numeric(pd.Series([row["bks"]]), errors="coerce").iloc[0]
        actual_status = "new" if pd.isna(bks) else ("improved" if status == "BEAT" else status.lower())
        if actual_status != expected_status:
            raise SystemExit(f"{instance}: expected {expected_status}, found {actual_status}")
        obj = float(row["alns_obj"])
        ub = float(row["best_ub"])
        gap = (ub - obj) / ub * 100.0
        note = fixed_note
        if note is None:
            margin = 100.0 * (obj - float(bks)) / float(bks)
            note = f"+{margin:.1f}\\% over published BKS ({int(bks)})"
        rows.append({
            "instance": instance,
            "objective": int(obj),
            "ub_lag": int(ub),
            "cert_gap_pct": gap,
            "status": actual_status,
            "note": note,
        })

    out = pd.DataFrame(rows)
    os.makedirs(args.outdir, exist_ok=True)
    csv_path = os.path.join(args.outdir, "new_certified_results.csv")
    tex_path = os.path.join(args.outdir, "new_certified_results.tex")
    out.to_csv(csv_path, index=False)
    lines = ["% Generated by build_new_results.py; do not edit by hand.",
             r"\begin{tabular}{lccccl}", r"\toprule",
             r"Instance & Objective & $UB_{\text{lag}}$ & Cert. gap & Status & Note \\", r"\midrule"]
    for row in rows:
        lines.append(
            rf"{esc(row['instance'])} & {row['objective']} & {row['ub_lag']} & "
            rf"{row['cert_gap_pct']:.2f}\% & {row['status']} & {row['note']} \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    with open(tex_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"Wrote {csv_path}\nWrote {tex_path}")


if __name__ == "__main__":
    main()
